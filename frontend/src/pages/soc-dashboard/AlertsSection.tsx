import { ChevronLeft, ChevronRight, Search, ShieldAlert, X } from 'lucide-react'
import { useMemo, useState } from 'react'
import { ALERT_STATUS_PRESENTATION, SEVERITY_PRESENTATION } from '../../components/alert/alertPresentation'
import { EmptyState, ErrorState, LoadingState } from '../../components/states'
import { Button } from '../../components/ui/Button'
import { SectionHeading } from '../../components/ui/SectionHeading'
import { StatusDot } from '../../components/ui/StatusDot'
import { useAlerts, type UseAlerts } from '../../hooks/useAlerts'
import type { Alert, AlertLifecycleStatus } from '../../types/alert'
import type { SeverityLevel } from '../../types/security'
import { formatCount, formatLocalDateTime, formatUtcDateTime } from '../../utils/format'
import { AlertDetailDialog } from './AlertDetailDialog'

const SEVERITY_FILTERS: { value: 'all' | SeverityLevel; label: string }[] = [
  { value: 'all', label: 'All severities' },
  { value: 'critical', label: 'Critical' },
  { value: 'high', label: 'High' },
  { value: 'medium', label: 'Medium' },
  { value: 'low', label: 'Low' },
]

const STATUS_FILTERS: { value: 'all' | AlertLifecycleStatus; label: string }[] = [
  { value: 'all', label: 'All statuses' },
  { value: 'open', label: 'Open' },
  { value: 'acknowledged', label: 'Acknowledged' },
  { value: 'investigating', label: 'Investigating' },
  { value: 'resolved', label: 'Resolved' },
  { value: 'false_positive', label: 'False positive' },
]

/**
 * Recent detections and alerts table (Step 45): backed by the real,
 * persisted `Alert` rows the detection/alert pipeline already produces
 * — nothing displayed here is fabricated, and an empty result is
 * reported as "no alerts", never papered over with placeholder rows.
 * Status and severity filters are forwarded to the backend
 * (`GET /alerts?status=...&severity=...`); the free-text search box
 * filters only the already-loaded page, the same documented limitation
 * `DetectionResultsSection` already applies for the same reason (no
 * full-text search endpoint exists).
 */
export function AlertsSection() {
  const alerts = useAlerts()
  const [severityFilter, setSeverityFilter] = useState<'all' | SeverityLevel>('all')
  const [statusFilter, setStatusFilter] = useState<'all' | AlertLifecycleStatus>('all')
  const [query, setQuery] = useState('')
  const [selectedAlertId, setSelectedAlertId] = useState<string | null>(null)

  function applyFilters(nextSeverity: 'all' | SeverityLevel, nextStatus: 'all' | AlertLifecycleStatus) {
    setSeverityFilter(nextSeverity)
    setStatusFilter(nextStatus)
    alerts.setFilters({
      severity: nextSeverity === 'all' ? undefined : nextSeverity,
      status: nextStatus === 'all' ? undefined : nextStatus,
    })
  }

  return (
    <div>
      <SectionHeading
        id="alerts-heading"
        title="Recent detections and alerts"
        description="Alerts generated by explicit, configurable rules over the hybrid detection, risk scoring, and explainability pipeline."
      />

      <div className="mt-4 flex flex-wrap items-center gap-3">
        <select
          aria-label="Filter by severity"
          value={severityFilter}
          onChange={(event) => applyFilters(event.target.value as 'all' | SeverityLevel, statusFilter)}
          className="h-8 rounded-lg border border-graphite-900/8 bg-white px-2 text-xs text-graphite-800 shadow-control focus:outline-none focus-visible:ring-2 focus-visible:ring-accent-500/60"
        >
          {SEVERITY_FILTERS.map((option) => (
            <option key={option.value} value={option.value}>
              {option.label}
            </option>
          ))}
        </select>
        <select
          aria-label="Filter by status"
          value={statusFilter}
          onChange={(event) => applyFilters(severityFilter, event.target.value as 'all' | AlertLifecycleStatus)}
          className="h-8 rounded-lg border border-graphite-900/8 bg-white px-2 text-xs text-graphite-800 shadow-control focus:outline-none focus-visible:ring-2 focus-visible:ring-accent-500/60"
        >
          {STATUS_FILTERS.map((option) => (
            <option key={option.value} value={option.value}>
              {option.label}
            </option>
          ))}
        </select>
        <label className="relative min-w-[180px] flex-1">
          <span className="sr-only">Search loaded alerts by title or batch</span>
          <Search className="pointer-events-none absolute top-1/2 left-2.5 size-3.5 -translate-y-1/2 text-graphite-400" aria-hidden="true" />
          <input
            type="search"
            value={query}
            onChange={(event) => setQuery(event.target.value)}
            placeholder="Search this page by title…"
            className="h-8 w-full rounded-lg border border-graphite-900/8 bg-white py-1.5 pr-8 pl-8 text-xs text-graphite-800 shadow-control placeholder:text-graphite-400 focus:outline-none focus-visible:ring-2 focus-visible:ring-accent-500/60"
          />
          {query && (
            <button
              type="button"
              aria-label="Clear search"
              onClick={() => setQuery('')}
              className="absolute top-1/2 right-1.5 -translate-y-1/2 rounded p-0.5 text-graphite-400 hover:text-graphite-700"
            >
              <X className="size-3.5" aria-hidden="true" />
            </button>
          )}
        </label>
      </div>

      <div className="mt-4">
        <AlertsContent alerts={alerts} query={query} onSelect={setSelectedAlertId} />
      </div>

      {selectedAlertId && (
        <AlertDetailDialog
          alertId={selectedAlertId}
          onClose={() => setSelectedAlertId(null)}
          onStatusChanged={alerts.refresh}
        />
      )}
    </div>
  )
}

function matchesQuery(alert: Alert, query: string): boolean {
  if (!query.trim()) return true
  const needle = query.trim().toLowerCase()
  return alert.title.toLowerCase().includes(needle) || alert.batch_id.toLowerCase().includes(needle)
}

function AlertsContent({ alerts, query, onSelect }: { alerts: UseAlerts; query: string; onSelect: (id: string) => void }) {
  const { data, failure, isLoading, refresh } = alerts

  const filteredItems = useMemo(() => {
    if (!data) return []
    return data.items.filter((alert) => matchesQuery(alert, query))
  }, [data, query])

  if (!data) {
    if (failure) {
      return (
        <ErrorState compact title="Unable to load alerts" message={failure.message} onRetry={isLoading ? undefined : refresh} />
      )
    }
    return <LoadingState compact title="Loading alerts" description="Contacting the AI-IDS API." />
  }

  if (data.total_items === 0) {
    return (
      <EmptyState
        compact
        icon={ShieldAlert}
        title="No alerts yet"
        description="Alerts appear here once a processed batch or live flow crosses the configured hybrid-outcome/risk-severity threshold."
      />
    )
  }

  return (
    <div className="flex flex-col gap-3">
      {failure && (
        <p role="alert" className="text-xs text-accent-700">
          {failure.message} The list below may be out of date.
        </p>
      )}
      {query.trim() && (
        <p aria-live="polite" className="text-[13px] text-graphite-500">
          Showing <span className="tabular-nums text-graphite-700">{formatCount(filteredItems.length)}</span> of{' '}
          <span className="tabular-nums text-graphite-700">{formatCount(data.items.length)}</span> alerts on this page matching your search.
        </p>
      )}
      {filteredItems.length === 0 ? (
        <p className="rounded-lg border border-graphite-900/8 bg-graphite-50/60 px-4 py-6 text-center text-[13px] text-graphite-500">
          No alerts on this page match your search.
        </p>
      ) : (
        <ul aria-busy={isLoading} className="divide-y divide-graphite-900/6">
          {filteredItems.map((alert) => (
            <AlertRow key={alert.id} alert={alert} onSelect={onSelect} />
          ))}
        </ul>
      )}
      <AlertsPager alerts={alerts} />
    </div>
  )
}

function AlertRow({ alert, onSelect }: { alert: Alert; onSelect: (id: string) => void }) {
  const severity = SEVERITY_PRESENTATION[alert.severity]
  const status = ALERT_STATUS_PRESENTATION[alert.status]

  return (
    <li>
      <button
        type="button"
        onClick={() => onSelect(alert.id)}
        aria-label={`Open investigation for alert: ${alert.title}`}
        className="flex w-full flex-col gap-1.5 py-3 text-left transition-colors hover:bg-graphite-900/3 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent-500/60"
      >
        <div className="flex flex-wrap items-center justify-between gap-x-4 gap-y-1">
          <span className="flex min-w-0 items-center gap-3">
            <StatusDot tone={severity.tone} halo />
            <span className="truncate text-sm font-medium text-graphite-900">{alert.title}</span>
          </span>
          <time dateTime={alert.created_at} title={formatUtcDateTime(alert.created_at)} className="shrink-0 text-[13px] tabular-nums text-graphite-500">
            {formatLocalDateTime(alert.created_at)}
          </time>
        </div>
        <p className="flex flex-wrap gap-x-3 gap-y-0.5 text-[13px] text-graphite-500">
          <span className="inline-flex items-center gap-1.5">
            <StatusDot tone={status.tone} /> {status.label}
          </span>
          <span>Row {alert.row_number}</span>
          <span className="truncate" title={alert.batch_id}>
            Batch {alert.batch_id.slice(0, 8)}
          </span>
          <span>Risk {alert.evidence.risk_score.toFixed(0)}/100</span>
        </p>
      </button>
    </li>
  )
}

function AlertsPager({ alerts }: { alerts: UseAlerts }) {
  const { data, isLoading, page, nextPage, previousPage } = alerts
  if (!data) return null

  const summary = `${formatCount(data.total_items)} ${data.total_items === 1 ? 'alert' : 'alerts'}`
  if (data.total_pages <= 1) {
    return <p className="mt-2 border-t border-graphite-900/6 pt-3 text-[13px] text-graphite-500">{summary}</p>
  }

  return (
    <nav aria-label="Alert pagination" className="mt-2 flex flex-wrap items-center justify-between gap-3 border-t border-graphite-900/6 pt-3">
      <p className="text-[13px] text-graphite-500">
        Page <span className="tabular-nums text-graphite-700">{data.page}</span> of{' '}
        <span className="tabular-nums text-graphite-700">{data.total_pages}</span> · {summary}
      </p>
      <div className="flex gap-2">
        <Button aria-label="Previous page of alerts" onClick={previousPage} disabled={isLoading || page <= 1}>
          <ChevronLeft className="size-3.5" aria-hidden="true" />
          Previous
        </Button>
        <Button aria-label="Next page of alerts" onClick={nextPage} disabled={isLoading || page >= data.total_pages}>
          Next
          <ChevronRight className="size-3.5" aria-hidden="true" />
        </Button>
      </div>
    </nav>
  )
}
