"""AlertStatusHistory: one audit record of an `Alert`'s status changing
from one `AlertStatus` to another, produced by
`app.services.alert_lifecycle`.

Step 37 is the first step that creates rows here. Append-only by
convention (this module never updates or deletes a row once written) —
the audit trail for a given alert is reconstructed by reading every row
with that `alert_id`, ordered by `changed_at`, never by inspecting the
alert's current `status` alone.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone

from sqlalchemy import DateTime, ForeignKey, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship
from sqlalchemy.sql import func
from sqlalchemy.types import Enum as SAEnum
from sqlalchemy.types import Uuid

from app.db.base import Base
from app.models.enums import AlertStatus


class AlertStatusHistory(Base):
    __tablename__ = "alert_status_history"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True), primary_key=True, default=uuid.uuid4
    )

    alert_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True), ForeignKey("alerts.id"), nullable=False, index=True
    )

    previous_status: Mapped[AlertStatus] = mapped_column(
        SAEnum(
            AlertStatus,
            name="alert_status_history_previous_status",
            create_constraint=True,
            native_enum=False,
            values_callable=lambda enum_cls: [member.value for member in enum_cls],
        ),
        nullable=False,
    )
    new_status: Mapped[AlertStatus] = mapped_column(
        SAEnum(
            AlertStatus,
            name="alert_status_history_new_status",
            create_constraint=True,
            native_enum=False,
            values_callable=lambda enum_cls: [member.value for member in enum_cls],
        ),
        nullable=False,
    )

    note: Mapped[str | None] = mapped_column(Text, nullable=True)
    """Optional, caller-supplied free text (e.g. why an alert was marked
    a false positive) — never required, never generated by this module."""

    changed_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        server_default=func.now(),
        index=True,
    )

    alert: Mapped["Alert"] = relationship("Alert", back_populates="status_history")
